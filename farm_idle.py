"""
Весёлая ферма — idle-игра на pygame.

Установка и запуск:
    python -m pip install pygame
    python farm_idle.py

Управление:
    ЛКМ по монетке над грядкой  — собрать урожай с грядки в общий банк (можно водить зажатой мышью).
                                  Урожай НЕ попадает в банк сам: он копится на грядке, пока его не собрать.
    Кнопка-лопата / клавиша U   — режим прокачки (1X / 10X / до вехи / MAX)
    Кнопка-тележка / клавиша S  — магазин: удобрения (прибыль x3) и фермеры (урожай копится)
    Тучка                       — вызвать дождь: рост x2 на минуту
    Солнышко                    — мгновенный бонус (минута дохода)
    Белка                       — раз в 2-5 минут пробегает по лугу. Поймай кликом —
                                  получишь 40% от того, что ферма производит за 5 минут.
                                  Иногда (10%) прибегает золотая белка: награда x5, но она шустрее.
    Ворона                      — раз в 5-10 минут садится на грядку, и та перестаёт расти.
                                  Кликни по вороне, чтобы прогнать. В офлайне вороны нет.
    Грузовик                    — приезжает, когда за забег заработано достаточно.
                                  Забирает ферму и деньги, даёт листья (+2% дохода каждый навсегда).
    Амбар / кнопка «Сарай» / B  — сарай с животными. Животные едят урожай с грядок
                                  (кнопка «Покормить» или нанятый скотник) и делают продукты:
                                  они в 2-4 раза дороже съеденного корма.
    Кнопка «Переезд»            — когда за один забег заработано $1aa, можно переехать на новую ферму:
                                  всё с нуля, с собой — x2 к доходу и трофей. Вторая глава — Средневековое поле:
                                  крестьяне, мельница с пекарней, разбойники, печати и «Привилегии короля».
    Кнопка-лист / плашка листьев — дерево улучшений: трать листья на постоянные бонусы.
                                  Потраченный лист перестаёт давать +2% — выбирай, что выгоднее.
    Esc                         — закрыть окно / выйти из режима прокачки
    F11                         — полный экран (окно можно и просто растянуть мышкой)

Режим разработчика (для тестов):
    python farm_idle.py --dev   — отдельное сохранение farm_save_dev.json (основное не трогается),
                                  F1 открывает панель: деньги, листья, переезд, звери, скорость времени x10/x60.
    python farm_idle.py --export-templates — выгрузить шаблоны спрайтов (см. SPRITES.md)
Прогресс сохраняется в farm_save.json рядом с игрой.
Код лежит в папке farmgame/, картинки — в assets/.
"""
