def part_of_day(now=None):
    h = (now or datetime.datetime.now()).hour
    if 5 <= h < 12:
        return "morning"
    if 12 <= h < 18:
        return "day"
    if 18 <= h < 23:
        return "evening"
    return "night"


def mood(rnd=random, now=None):
    return rnd.choice(MOOD[part_of_day(now)] + MOOD_ANY[:1])


def news(farm, tavern, rnd=random, today=None):
    """Что нового: самые полезные новости о делах игрока (первые две)."""
    from . import achievements as ach
    from . import wheel as wh
    out = []
    ready = tavern.claimable()
    if ready:
        out.append(f"На доске тебя ждёт награда: {len(ready)} {_word(len(ready), 'задание', 'задания', 'заданий')} "
                   "выполнено!")
    left = [q for q in tavern.daily if q["progress"] < q["target"]]
    if tavern.daily and not left and not ready:
        out.append("Все задания на сегодня сделаны. Молодец! Новые повесят в полночь.")
    elif left:
        q = min(left, key=lambda q: q["target"] - q["progress"])
        out.append(f"Ближе всего к концу — «{q['title']}»: осталось {q['target'] - q['progress']}.")
    w = tavern.weekly
    if w and not w["claimed"] and w["progress"] < w["target"]:
        pct = int(100 * w["progress"] / max(1, w["target"]))
        out.append(f"Задание недели «{w['title']}» сделано на {pct}%.")
    if tavern.casino_open and wh.can_spin(tavern, today):
        out.insert(0, "Колесо фортуны сегодня ещё не крутил! Загляни в Игровую.")
    got = ach.claimable(tavern)
    if got:
        out.insert(0, f"Слыхал, у тебя новое достижение! Забери жетоны в «Достижениях» — их {len(got)}.")
    if farm.song_left > 0:
        out.append("Бард сейчас играет твою песню — слышишь, как гости притоптывают?")
    if not out:
        done = len(tavern.ach_done)
        out.append(f"Новостей нет — а значит, всё хорошо. Достижений у тебя уже {done} из {len(ach.ACHIEVEMENTS)}.")
    return " ".join(out[:2])


def tip(farm, tavern, rnd=random):
    """Совет: сначала по делу (что видно в игре), иначе — общий."""
    from .config import PRIZES
    out = []
    if farm.leaves >= 50 and farm.any_tree_affordable():
        out.append(f"У тебя {farm.leaves} листьев. Не спеши тратить все — каждая покупка в дереве поднимает цену остальных.")
    if tavern.tokens >= 60 and any(tavern.prize_state(p) == "can" and not (p.get("jackpot") or p.get("achievement"))
                                   and tavern.tokens >= p["cost"] for p in PRIZES):
        out.append(f"Жетонов у тебя {tavern.tokens} — на призовой стойке есть что взять. Загляни в «Призы».")
    if farm.farm_def().get("peasants") and farm.free_peasants() > 0:
        out.append("У тебя есть свободные помощники — поставь их на грядки, пусть работают!")
    if not out:
        return rnd.choice(TIPS_ANY)
    return rnd.choice(out)


def story(tavern):
    text = STORIES[tavern.talk_story % len(STORIES)]
    tavern.talk_story += 1
    return text


def answer(topic, farm, tavern, rnd=random):
    """Ответ бармена на тему. Считается в статистике разговоров (достижение «Свой человек»)."""
    if topic == "mood":
        return mood(rnd)
    if topic == "news":
        return news(farm, tavern, rnd)
    if topic == "tip":
        return tip(farm, tavern, rnd)
    return story(tavern)


def _word(n, one, few, many):
    from .tavern import plural
    return plural(n, one, few, many)
