SECRET = dict(id="secret", name="???", ready=False,     # 3.42: намёк на главу 5 (горная деревня драконов)
              text="Дальше — горы в тумане. Говорят, там строят деревню драконы... и кидают кости.")


def chapters(farm_index):
    """Главы по порядку: [{id, name, text, n, state}] — state: done (пройдена), here (ты здесь),
    next (следующая, открыта), soon (следующая, но ещё готовится), locked (дальше)."""
    out = []
    items = list(FARMS) + ([SECRET] if FARMS[-1].get("ready") else [])   # 3.48: глава 5 уже в списке — «скоро»
    for n, fm in enumerate(items):
        if n < farm_index:
            state = "done"
        elif n == farm_index:
            state = "here"
        elif n == farm_index + 1:
            state = "next" if fm.get("ready") else "soon"
        elif not fm.get("ready") and fm["id"] != "secret":
            state = "soon"          # 3.27: глава ещё в работе — «скоро», даже если до неё две главы
        else:
            state = "locked"
        out.append(dict(id=fm["id"], name=fm["name"], text=CHAPTER_TEXT.get(fm["id"], fm.get("text", "")), n=n + 1,
                        state=state, ready=bool(fm.get("ready"))))
    return out
